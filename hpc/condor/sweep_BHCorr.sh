#!/bin/bash
#
# HTCondor version of hpc/sweep_BoseHubbardCorrelated_NormalizedITE.sh: one hpc/BoseHubbardCorrelated_NormalizedITE.jl
# job per point (t, μ) of the correlated Bose-Hubbard phase diagram, all in one condor cluster. Run on the access point
# (the access point) from the repo root:
#   bash hpc/condor/sweep_BHCorr.sh 6                         # the default (t, μ) grid for L = 6
#   DRYRUN=1 bash hpc/condor/sweep_BHCorr.sh 6                # only print the points and the submit file
#   TS="0.05 0.1" MUS="0.2 0.4 0.6" bash hpc/condor/sweep_BHCorr.sh 6
#   R=0.5 DELTA=0.3 OMEGA=0.5 MAXD=32 MAXITER=1000 bash hpc/condor/sweep_BHCorr.sh 6
#   MAXITER=4000 bash hpc/condor/sweep_BHCorr.sh 6            # rerun the unconverged points with more steps
#   FORCE=1 bash hpc/condor/sweep_BHCorr.sh 6                 # resubmit every point, also those that are done
#   PPN=4 REQUIREMENTS="cpu_performance > 7" bash hpc/condor/sweep_BHCorr.sh 6
#
# Which points are submitted is decided as in the PBS sweep, by hpc/BoseHubbardCorrelated_NormalizedITE.jl --status
# (run: no state, rerun: unconverged and MAXITER/CONVTOL improved, uptodate: skipped). Points that are still queued or
# running are not detected: do not run the sweep again before the previous cluster has finished (condor_q).
#
# The pool has no shared filesystem: every job gets Project.toml, Manifest.toml, src/ and the script, runs them with
# hpc/condor/run_julia.sh on the node Julia, and only its state file is transferred back, to the same relative path
# data/BoseHubbardCorrelated_NormalizedITE/<run tag>/L<L>/t<t>/mu<μ>.jld2 under this repo (DATA_DIR is always "data").
# Logs, the points file and the submit file: logs/BoseHubbardCorrelated_NormalizedITE/<run tag>/L<L>/condor/
# Observables afterwards: bash hpc/condor/obs_BHCorr.sh <L>, then bash hpc/condor/plot_BHCorr.sh <L>.

set -euo pipefail

L="${1:?usage: bash hpc/condor/sweep_BHCorr.sh <L>}"
[ -f Project.toml ] && [ -d hpc/condor ] || { echo "run from the repo root"; exit 1; }

# (t/U, μ/U) grid of the mean values (disorder values t(1±OMEGA) and μ±DELTA), formatted as %.4f in the file names
TS="${TS:-$(LC_ALL=C seq 0.02 0.02 0.30)}"
MUS="${MUS:-$(LC_ALL=C seq 0 0.1 1.6)}"

# Run parameters (U, R, DELTA, OMEGA, NMAX, DTAU, MAXD set the run tag), as in the PBS sweep
export U="${U:-1.0}"
export R="${R:-0.0}"           # correlation of hopping and potential: P = (1±R)/4
export DELTA="${DELTA:-0.0}"   # potential disorder: μ ± DELTA
export OMEGA="${OMEGA:-0.0}"   # hopping disorder: t(1 ± OMEGA), 0 ≤ OMEGA ≤ 1
export NMAX="${NMAX:-4}"
export DTAU="${DTAU:-0.05}"
export MAXD="${MAXD:-16}"
export MAXITER="${MAXITER:-2000}"
export CONVTOL="${CONVTOL:-1e-6}"
export CROSS_WIDTH="${CROSS_WIDTH:-32}"
export DATA_DIR=data           # relative, so the transferred state lands at the same path here and in the sandbox

# Resources per job
PPN="${PPN:-8}"                          # request_cpus
JULIA_THREADS="${JULIA_THREADS:-1}"      # Julia runs with --threads=$JULIA_THREADS
BLAS_THREADS="${BLAS_THREADS:-$PPN}"     # and BLAS.set_num_threads($BLAS_THREADS)
MEM="${MEM:-6 G}"
DISK="${DISK:-2 G}"
REQUIREMENTS="${REQUIREMENTS:-}"         # extra requirements, e.g. "cpu_performance > 7"
NICE="${NICE:-TRUE}"                     # nice_user: only use idle slots
UG_NAME="${UG_NAME:-<login>}"           # UGent login: HOME=/tmp/$UG_NAME on the execute node
JULIA="${JULIA:-$HOME/.juliaup/bin/julia +$(sed -n 's/^julia_version = "\(.*\)"/\1/p' Manifest.toml)}"   # Julia on the access point (juliaup, Manifest version)

script=hpc/BoseHubbardCorrelated_NormalizedITE.jl
points=()
rerun=0
skipped=0
tag=""
for t in $TS; do
    t=$(LC_ALL=C printf "%.4f" "$t")
    for mu in $MUS; do
        mu=$(LC_ALL=C printf "%.4f" "$mu")
        mapfile -t st < <($JULIA --project=. --startup-file=no $script --status "$L" "$t" "$mu")
        tag="${st[0]}"
        if [ "${st[2]}" = "uptodate" ] && [ "${FORCE:-0}" != "1" ]; then
            echo "skip   L=$L t=$t μ=$mu (${st[3]})"
            skipped=$((skipped + 1))
            continue
        fi
        if [ "${st[2]}" = "rerun" ]; then
            echo "rerun  L=$L t=$t μ=$mu (${st[3]})"
            rerun=$((rerun + 1))
        fi
        points+=("$t $mu")
    done
done
if [ "${#points[@]}" = "0" ]; then
    echo "L = $L: nothing to submit, $skipped skipped (done)"
    exit 0
fi

logdir="logs/BoseHubbardCorrelated_NormalizedITE/$tag/L$L/condor"
stamp=$(date +%Y%m%d_%H%M%S)
pointsfile="$logdir/points_$stamp.txt"
submitfile="$logdir/sweep_$stamp.submit"
reqs="has_julia${REQUIREMENTS:+ && ($REQUIREMENTS)}"

submit=$(cat <<EOF
# Correlated Bose-Hubbard normalized ITE, L = $L, run tag $tag (generated by hpc/condor/sweep_BHCorr.sh)
JOBNAME = BHC_L${L}
UG_NAME = $UG_NAME

executable          = hpc/condor/run_julia.sh
transfer_executable = TRUE
arguments           = "$script $L \$(t) \$(mu)"
environment         = "HOME=/tmp/\$(UG_NAME) JULIA_THREADS=$JULIA_THREADS BLAS_THREADS=$BLAS_THREADS U=$U R=$R DELTA=$DELTA OMEGA=$OMEGA NMAX=$NMAX DTAU=$DTAU MAXD=$MAXD MAXITER=$MAXITER CONVTOL=$CONVTOL CROSS_WIDTH=$CROSS_WIDTH DATA_DIR=$DATA_DIR"

should_transfer_files   = TRUE
preserve_relative_paths = TRUE
when_to_transfer_output = ON_EXIT
transfer_input_files    = Project.toml, Manifest.toml, src, $script
transfer_output_files   = $DATA_DIR/BoseHubbardCorrelated_NormalizedITE/$tag/L$L/t\$(t)/mu\$(mu).jld2

nice_user      = $NICE
request_cpus   = $PPN
request_memory = $MEM
request_disk   = $DISK
requirements   = $reqs
rank           = cpu_performance

output = $logdir/\$(JOBNAME)_t\$(t)_mu\$(mu)_\$(Cluster).out
error  = $logdir/\$(JOBNAME)_t\$(t)_mu\$(mu)_\$(Cluster).err
log    = $logdir/\$(Cluster).log

queue t, mu from $pointsfile
EOF
)

if [ "${DRYRUN:-0}" = "1" ]; then
    printf '%s\n' "${points[@]}" | sed 's/^/point  /'
    echo "$submit" | sed 's/^/       | /'
    echo "L = $L: ${#points[@]} job(s) to submit ($rerun rerun), $skipped skipped (done)"
else
    mkdir -p "$logdir"
    printf '%s\n' "${points[@]}" > "$pointsfile"
    echo "$submit" > "$submitfile"
    condor_submit "$submitfile"
    echo "L = $L: ${#points[@]} job(s) submitted ($rerun rerun), $skipped skipped (done); submit file $submitfile"
fi
