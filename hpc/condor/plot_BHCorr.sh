#!/bin/bash
#
# Phase-diagram plot of a correlated Bose-Hubbard run on the HTCondor pool: runs
# hpc/plot_BoseHubbardCorrelated_NormalizedITE.jl (κ, table, combined CSV and heatmaps from the mu<μ>_obs.csv files) for
# a given L. Run on the access point from the repo root after the jobs of hpc/condor/obs_BHCorr.sh have
# finished, with the same run parameters as the sweep, so the run tag matches:
#   bash hpc/condor/plot_BHCorr.sh 6                          # directly on the access point (only reads small CSVs)
#   KAPPA_TOL=0.02 SBSTD_TOL=0.1 A2_TOL=0.02 bash hpc/condor/plot_BHCorr.sh 6
#   CONDOR=1 bash hpc/condor/plot_BHCorr.sh 6                 # as one condor job instead (e.g. no CairoMakie here)
#   CONDOR=1 DRYRUN=1 bash hpc/condor/plot_BHCorr.sh 6        # only print the submit file
# Output: data/BoseHubbardCorrelated_NormalizedITE/<run tag>/L<L>/observables.csv and
#   plots/BoseHubbardCorrelated_NormalizedITE_<run tag>_L<L>.png
# Phase classification (see the plot script): κ ≤ KAPPA_TOL → κ low, S_bstd < SBSTD_TOL → std low, |⟨a⟩|² ≤ A2_TOL → |⟨a⟩|² low;
#   MI: κ low, std low; SF: κ high, std low; BG: κ high, std high; κ low, std high: SF if |⟨a⟩|² high, else unclassified

set -euo pipefail

L="${1:?usage: bash hpc/condor/plot_BHCorr.sh <L>}"
[ -f Project.toml ] && [ -d hpc/condor ] || { echo "run from the repo root"; exit 1; }

export U="${U:-1.0}"
export R="${R:-0.0}"
export DELTA="${DELTA:-0.0}"
export OMEGA="${OMEGA:-0.0}"
export NMAX="${NMAX:-4}"
export DTAU="${DTAU:-0.05}"
export MAXD="${MAXD:-16}"
export DATA_DIR=data
export KAPPA_TOL="${KAPPA_TOL:-0.05}"
export SBSTD_TOL="${SBSTD_TOL:-0.05}"
export A2_TOL="${A2_TOL:-0.05}"
JULIA="${JULIA:-$HOME/.juliaup/bin/julia +$(sed -n 's/^julia_version = "\(.*\)"/\1/p' Manifest.toml)}"   # Julia on the access point (juliaup, Manifest version)

script=hpc/plot_BoseHubbardCorrelated_NormalizedITE.jl

if [ "${CONDOR:-0}" != "1" ]; then
    exec $JULIA --project=examples --startup-file=no $script "$L"
fi

MEM="${MEM:-4 G}"
NICE="${NICE:-TRUE}"
UG_NAME="${UG_NAME:-$USER}"

# Run tag (via the simulation script's --path mode, t and μ are irrelevant for it) and the observables files
mapfile -t paths < <($JULIA --startup-file=no hpc/BoseHubbardCorrelated_NormalizedITE.jl --path "$L" 0 0)
tag="${paths[0]}"
folder="$DATA_DIR/BoseHubbardCorrelated_NormalizedITE/$tag/L$L"
logdir="logs/BoseHubbardCorrelated_NormalizedITE/$tag/L$L/condor/plot"
mapfile -t obsfiles < <(ls "$folder"/t*/mu*_obs.csv 2> /dev/null)
[ "${#obsfiles[@]}" != "0" ] || { echo "no observables in $folder"; exit 1; }
inputs=$(IFS=,; echo "${obsfiles[*]}")
plotfile="plots/BoseHubbardCorrelated_NormalizedITE_${tag}_L$L.png"

submit=$(cat <<EOF
# Correlated Bose-Hubbard plot, L = $L, run tag $tag (generated by hpc/condor/plot_BHCorr.sh)
JOBNAME = BHC_plot_L${L}
UG_NAME = $UG_NAME

executable          = hpc/condor/run_julia.sh
transfer_executable = TRUE
arguments           = "$script $L"
environment         = "HOME=/tmp/\$(UG_NAME) U=$U R=$R DELTA=$DELTA OMEGA=$OMEGA NMAX=$NMAX DTAU=$DTAU MAXD=$MAXD DATA_DIR=$DATA_DIR KAPPA_TOL=$KAPPA_TOL SBSTD_TOL=$SBSTD_TOL A2_TOL=$A2_TOL RUN_PROJECT=examples"

should_transfer_files   = TRUE
preserve_relative_paths = TRUE
when_to_transfer_output = ON_EXIT
transfer_input_files    = Project.toml, Manifest.toml, examples/Project.toml, examples/Manifest.toml, src, $script, $inputs
transfer_output_files   = $folder/observables.csv, $plotfile

nice_user      = $NICE
request_cpus   = 1
request_memory = $MEM
request_disk   = 4 G
requirements   = has_julia
rank           = cpu_performance

# Labels for matching jobs to sweep points (hpc/condor/*.sh, dashboard)
+BHC_stage = "plot"
+BHC_tag   = "$tag"
+BHC_L     = $L

output = $logdir/\$(JOBNAME)_\$(Cluster).out
error  = $logdir/\$(JOBNAME)_\$(Cluster).err
log    = $logdir/\$(Cluster).log

queue 1
EOF
)

if [ "${DRYRUN:-0}" = "1" ]; then
    echo "$submit"
else
    mkdir -p "$logdir"
    submitfile="$logdir/plot_$(date +%Y%m%d_%H%M%S).submit"
    echo "$submit" > "$submitfile"
    condor_submit "$submitfile"
fi
